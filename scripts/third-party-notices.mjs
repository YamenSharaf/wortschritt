#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md and packages/client/src/notices.json: the
// licences of everything the app, the web app and the server ship (their
// production dependencies) and of the assets bundled with them. Run it after
// changing dependencies: `pnpm notices`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const raw = execFileSync("pnpm", ["licenses", "list", "--json", "--prod", "--filter", "@mdb/app", "--filter", "@mdb/web", "--filter", "@mdb/api"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const byLicense = JSON.parse(raw);

/** The package's licence file(s), or null. */
function licenseText(dir) {
  if (!dir || !existsSync(dir)) return null;
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(f)).sort();
  if (!files.length) return null;
  return files.map((f) => readFileSync(join(dir, f), "utf8").trim()).join("\n\n");
}

const own = (name) => name.startsWith("@mdb/");
const packages = Object.values(byLicense)
  .flat()
  .filter((p) => !own(p.name))
  .map((p) => ({
    name: p.name,
    version: p.versions.join(", "),
    license: p.license,
    homepage: p.homepage ?? null,
    text: licenseText(p.paths?.[0]),
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

// Group packages by identical licence text (most MIT texts differ only in
// the copyright line, so groups stay small; that's fine).
const groups = new Map();
for (const p of packages) {
  const key = p.text ?? `(no licence file; declared ${p.license})`;
  if (!groups.has(key)) groups.set(key, { license: p.license, text: p.text, packages: [] });
  groups.get(key).packages.push({ name: p.name, version: p.version, homepage: p.homepage });
}

/** Assets bundled with the apps and the server (not npm packages). */
const assets = [
  {
    name: "Libron (reading font)",
    license: "OFL-1.1",
    note: "The release's TTF files, unmodified.",
    text: readFileSync(join(root, "packages/app/assets/fonts/libron/COPYRIGHT.txt"), "utf8").trim() + "\n\n" + readFileSync(join(root, "packages/app/assets/fonts/libron/OFL.txt"), "utf8").trim(),
  },
  {
    name: "German inflection and Partizip II data (RosaeNLG german-words-dict, german-verbs-dict)",
    license: "Apache-2.0",
    note: "By Ludan Stoecklé / RosaeNLG; only the form → lemma and infinitive → Partizip II mappings are extracted (packages/api/assets).",
    text: packages.find((p) => p.license === "Apache-2.0" && p.text && /Apache License/.test(p.text) && /TERMS AND CONDITIONS/.test(p.text))?.text ?? "Apache License 2.0: https://www.apache.org/licenses/LICENSE-2.0",
  },
  {
    name: "Wiktionary definitions (fetched when you look up a word)",
    license: "CC-BY-SA-4.0",
    note: "Shown with their source in the word panel; via freedictionaryapi.com. https://creativecommons.org/licenses/by-sa/4.0/",
    text: null,
  },
];

const list = [...groups.values()].sort((a, b) => a.packages[0].name.localeCompare(b.packages[0].name));
writeFileSync(join(root, "packages/client/src/notices.json"), JSON.stringify({ assets, groups: list }) + "\n");

const md = [
  "# Third-party notices",
  "",
  "Wortschritt (MIT, see [LICENSE](LICENSE)) ships these works by others. Generated by `pnpm notices`",
  "(`scripts/third-party-notices.mjs`) from the production dependencies of the Android app, the web app",
  "and the server; the apps show the same list under Open-source licences.",
  "",
  "## Bundled assets",
  "",
  ...assets.flatMap((a) => [`### ${a.name}`, "", `${a.license}. ${a.note}`, "", ...(a.text ? ["<details><summary>Licence</summary>", "", "```", a.text, "```", "", "</details>", ""] : [])]),
  `## Packages (${packages.length})`,
  "",
  ...list.flatMap((g) => [
    `### ${g.packages.map((p) => `${p.name} ${p.version}`).join(", ")}`,
    "",
    `${g.license}`,
    "",
    ...(g.text ? ["<details><summary>Licence</summary>", "", "```", g.text.replace(/```/g, "ˋˋˋ"), "```", "", "</details>", ""] : []),
  ]),
].join("\n");
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md);
console.log(`${packages.length} packages in ${list.length} groups; ${packages.filter((p) => !p.text).length} without a licence file.`);
