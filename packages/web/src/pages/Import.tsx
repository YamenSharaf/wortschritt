import { useMemo, useState } from "react";
import { buildImportPrompt, cheatsheet, EXAMPLE_SET, exerciseSet, importBody } from "@mdb/shared";
import { api } from "../lib/api";

type Kind = "exercise" | "cheatsheet";

export function ImportPage() {
  const [kind, setKind] = useState<Kind>("exercise");
  const [text, setText] = useState(JSON.stringify(EXAMPLE_SET, null, 2));
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const schema = kind === "exercise" ? exerciseSet : cheatsheet;

  const localValidation = useMemo(() => {
    try {
      const parsed = JSON.parse(text);
      const r = schema.safeParse(parsed);
      return r.success
        ? { ok: true as const }
        : { ok: false as const, issues: r.error.issues };
    } catch (e) {
      return { ok: false as const, issues: [{ path: [], message: `Invalid JSON: ${String(e)}` }] };
    }
  }, [text, schema]);

  async function submit() {
    setError(null);
    setMessage(null);
    let data: unknown;
    try {
      data = JSON.parse(text);
    } catch (e) {
      setError(`Invalid JSON: ${String(e)}`);
      return;
    }
    const body = importBody.safeParse({ kind, data });
    if (!body.success) {
      setError(
        body.error.issues
          .map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`)
          .join("\n"),
      );
      return;
    }
    try {
      const res = await api.import(body.data);
      setMessage(`Imported: "${res.id}" (${res.kind})`);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    }
  }

  function copyLlmPrompt() {
    const prompt = buildImportPrompt(kind);
    void navigator.clipboard.writeText(prompt);
    setMessage("LLM prompt copied to clipboard.");
  }

  return (
    <div className="max-w-2xl">
      <h1 className="mb-2 text-2xl font-bold">Import content</h1>
      <p className="mb-6 text-sm text-slate-500">
        Paste JSON (e.g. generated by an LLM). It's validated against the schema
        before it's saved. Content and features are separate — here you only add
        content, without changing any code.
      </p>

      <div className="mb-4 flex items-center gap-3">
        <select
          value={kind}
          onChange={(e) => setKind(e.target.value as Kind)}
          className="input max-w-40"
        >
          <option value="exercise">Exercise</option>
          <option value="cheatsheet">Cheat sheet</option>
        </select>
        <button
          type="button"
          onClick={copyLlmPrompt}
          className="rounded-lg border border-slate-300 px-3 py-2 text-sm dark:border-slate-700"
        >
          Copy LLM prompt
        </button>
      </div>

      <textarea
        value={text}
        onChange={(e) => setText(e.target.value)}
        spellCheck={false}
        className="h-80 w-full rounded-lg border border-slate-300 bg-white p-3 font-mono text-xs dark:border-slate-700 dark:bg-slate-900"
      />

      <div className="mt-2 text-xs">
        {localValidation.ok ? (
          <span className="text-green-600">✓ Schema valid</span>
        ) : (
          <span className="text-amber-600">
            {localValidation.issues.length} validation issue(s)
          </span>
        )}
      </div>

      <button
        type="button"
        disabled={!localValidation.ok}
        onClick={submit}
        className="mt-4 rounded-lg bg-accent px-4 py-2 font-medium text-accent-foreground disabled:opacity-40"
      >
        Import
      </button>

      {message && <p className="mt-3 text-sm text-green-600">{message}</p>}
      {error && (
        <pre className="mt-3 whitespace-pre-wrap rounded-lg bg-red-50 p-3 text-xs text-red-700 dark:bg-red-950 dark:text-red-300">
          {error}
        </pre>
      )}
    </div>
  );
}
