import { useEffect, useMemo, useState } from "react";
import type { ImportedItem } from "@mdb/shared";
import { buildImportPrompt, cheatsheet, EXAMPLE_SET, exerciseSet, importBody } from "@mdb/shared";
import { api } from "../lib/api";
import { CheckIcon } from "../components/icons";
import { btn } from "../components/ui";

type Kind = "exercise" | "cheatsheet";

export function ImportPage() {
  const [kind, setKind] = useState<Kind>("exercise");
  const [text, setText] = useState(JSON.stringify(EXAMPLE_SET, null, 2));
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [reload, setReload] = useState(0);

  const schema = kind === "exercise" ? exerciseSet : cheatsheet;

  const localValidation = useMemo(() => {
    try {
      const parsed = JSON.parse(text);
      const r = schema.safeParse(parsed);
      return r.success
        ? { ok: true as const }
        : { ok: false as const, issues: r.error.issues };
    } catch (e) {
      return { ok: false as const, issues: [{ path: [], message: `Invalid JSON: ${String(e)}` }] };
    }
  }, [text, schema]);

  async function submit() {
    setError(null);
    setMessage(null);
    let data: unknown;
    try {
      data = JSON.parse(text);
    } catch (e) {
      setError(`Invalid JSON: ${String(e)}`);
      return;
    }
    const body = importBody.safeParse({ kind, data });
    if (!body.success) {
      setError(
        body.error.issues
          .map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`)
          .join("\n"),
      );
      return;
    }
    try {
      const res = await api.import(body.data);
      setMessage(`Imported: "${res.id}" (${res.kind})`);
      setReload((n) => n + 1);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    }
  }

  function copyLlmPrompt() {
    const prompt = buildImportPrompt(kind);
    void navigator.clipboard.writeText(prompt);
    setMessage("LLM prompt copied to clipboard.");
  }

  return (
    <div className="max-w-2xl">
      <h1 className="mb-2 text-[28px] font-semibold leading-[34px] tracking-[-0.02em]">Import content</h1>
      <p className="mb-6 text-sm text-ink-muted">
        Paste JSON (e.g. generated by an LLM). It's validated against the schema
        before it's saved. Content and features are separate — here you only add
        content, without changing any code.
      </p>

      <div className="mb-4 flex items-center gap-3">
        <select
          value={kind}
          onChange={(e) => setKind(e.target.value as Kind)}
          className="input max-w-40"
        >
          <option value="exercise">Exercise</option>
          <option value="cheatsheet">Cheat sheet</option>
        </select>
        <button
          type="button"
          onClick={copyLlmPrompt}
          className={`${btn.secondary}`}
        >
          Copy LLM prompt
        </button>
      </div>

      <textarea
        value={text}
        onChange={(e) => setText(e.target.value)}
        spellCheck={false}
        className="h-80 w-full rounded-control border border-line-control bg-surface p-3 font-mono text-xs "
      />

      <div className="mt-2 text-xs">
        {localValidation.ok ? (
          <span className="inline-flex items-center gap-1 text-success"><CheckIcon className="h-4 w-4" />Schema valid</span>
        ) : (
          <span className="text-warning">
            {localValidation.issues.length} validation issue(s)
          </span>
        )}
      </div>

      <button
        type="button"
        disabled={!localValidation.ok}
        onClick={submit}
        className={`${btn.primary} mt-4`}
      >
        Import
      </button>

      {message && <p className="mt-3 text-sm text-success">{message}</p>}
      {error && (
        <pre className="mt-3 whitespace-pre-wrap rounded-control bg-danger-soft p-3 text-xs text-danger ">
          {error}
        </pre>
      )}

      <ImportedList reload={reload} />
    </div>
  );
}

/** The shared library's imports, with Delete for your own (or all, as admin). */
function ImportedList({ reload }: { reload: number }) {
  const [items, setItems] = useState<ImportedItem[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.imports().then(setItems).catch(() => setError("Couldn't load imports."));
  }, [reload]);

  async function remove(item: ImportedItem) {
    if (!window.confirm(`Delete "${item.title}" for everyone?`)) return;
    try {
      await api.deleteImport(item.id);
      setItems((list) => list?.filter((i) => i.id !== item.id) ?? null);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    }
  }

  if (!items || items.length === 0) return null;
  return (
    <section className="mt-10">
      <h2 className="mb-2 text-xl font-semibold tracking-[-0.01em]">Imported content</h2>
      {error && <p className="mb-2 text-sm text-danger">{error}</p>}
      <ul className="divide-y divide-[var(--border)] rounded-card border border-line text-sm ">
        {items.map((i) => (
          <li key={i.id} className="flex items-center gap-2 p-3">
            <div className="min-w-0 flex-1">
              <p className="truncate font-medium">{i.title}</p>
              <p className="truncate text-xs text-ink-subtle">
                {i.kind === "exercise" ? "Exercise" : "Cheat sheet"} · {i.id}
                {i.createdBy ? ` · by ${i.createdBy}` : ""}
              </p>
            </div>
            {i.canDelete && (
              <button
                type="button"
                onClick={() => void remove(i)}
                className="rounded-control border border-line-control px-2.5 py-1 text-xs font-medium text-danger hover:border-line-strong "
              >
                Delete
              </button>
            )}
          </li>
        ))}
      </ul>
    </section>
  );
}
